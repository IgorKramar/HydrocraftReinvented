-- Private HCRLab only. Never include tools/ in the release package.
require "HCR_FluidLedger"
require "HCR_FluidEffects"
require "HCR_FluidQuality"
require "Fluids/ISFluidContainer"
require "HCR_DrinkFluids"
require "HCR_FluidActions"
HCRLabQuality = {}

local function near(actual, expected, message)
    assert(math.abs(actual-expected) < 0.0001, message .. ": " .. tostring(actual) .. " != " .. tostring(expected))
end

function HCRLabQuality.run(player, profile)
    assert(profile == "HCRLab" and player and not isClient() and not isServer())
    reloadLuaFile("media/lua/shared/HCR_FluidLedger.lua")
    reloadLuaFile("media/lua/shared/HCR_FluidEffects.lua")
    reloadLuaFile("media/lua/shared/HCR_FluidQuality.lua")
    -- Only this disposable lab inventory: native Transfer refuses overfull players.
    local inventory = player:getInventory()
    for index=inventory:getItems():size()-1,0,-1 do
        local item=inventory:getItems():get(index)
        if not item:isEquipped() and not item:getModData().HCRLabFluids160Legacy then inventory:Remove(item) end
    end
    assert(not player:hasFullInventory(), "Private quality fixture inventory is overfull")
    local L, E, Q = HCRFluidLedger, HCRFluidEffects, HCRFluidQuality
    local plain = instanceItem("Base.WaterBottle")
    assert(not Q.active(plain, Q.fluid(plain)), "Plain water became tracked")
    print("[HCRQuality160] ordinary water compatibility PASS")
    local source = instanceItem("Hydrocraft.HCMilkjug")
    assert(source and source:IsFood())
    source:setAge(0)
    source:setHungChange(-0.005)
    source:setBaseHunger(-0.005)
    source:setThirstChange(-0.005)
    source:setCalories(5000)
    source:setPoisonPower(100)
    source:setFoodSicknessChange(0)
    source:setTainted(false)
    local snapshot = E.snapshot(source)
    local batch = L.batch("JuiceApple", 1, snapshot, getGameTime():getWorldAgeHours())
    local _, sip = L.split(batch, .01, 1)
    local stats, nutrition = player:getStats(), player:getNutrition()
    stats:set(CharacterStat.POISON, 0)
    player:getBodyDamage():JustAteFood(source, .01, false)
    local expectedPoison = stats:get(CharacterStat.POISON)
    stats:set(CharacterStat.POISON, 0)
    stats:set(CharacterStat.HUNGER, .5)
    stats:set(CharacterStat.THIRST, .5)
    nutrition:setCalories(0)
    E.consume(player, E.prepare(sip), false)
    near(stats:get(CharacterStat.POISON), expectedPoison, "fractional native poison")
    near(nutrition:getCalories(), 50, "small sip calories")
    near(stats:get(CharacterStat.HUNGER), .49995, "small sip hunger")
    near(stats:get(CharacterStat.THIRST), .49995, "small sip thirst")
    print("[HCRQuality160] native small sip PASS: calories=50; poison=" .. tostring(expectedPoison))

    source:setAge(9)
    source:setOffAge(3)
    source:setOffAgeMax(7)
    source:setPoisonPower(0)
    source:setBoredomChange(4)
    source:setUnhappyChange(6)
    local rotten = L.batch("JuiceApple", 1, E.snapshot(source), getGameTime():getWorldAgeHours())
    _, sip = L.split(rotten, .01, 1)
    stats:set(CharacterStat.BOREDOM, 0)
    stats:set(CharacterStat.UNHAPPINESS, 0)
    E.consume(player, E.prepare(sip), false)
    near(stats:get(CharacterStat.BOREDOM), source:getBoredomChange() * .01, "rotten boredom once")
    near(stats:get(CharacterStat.UNHAPPINESS), source:getUnhappyChange() * .01, "rotten unhappiness once")
    print("[HCRQuality160] native rotten modifiers PASS")

    local a, b = instanceItem("Base.WaterBottle"), instanceItem("Base.WaterBottle")
    local af, bf = a:getFluidContainer(), b:getFluidContainer()
    af:Empty(); bf:Empty()
    af:setCapacity(64)
    af:addFluid("JuiceApple", 64)
    Q.transport.JuiceApple = true -- private probe; no vanilla fluid properties changed
    Q.store(a, af, L.batch("JuiceApple", 64, snapshot, getGameTime():getWorldAgeHours()))
    local aw, bw = ISFluidContainer:new(af), ISFluidContainer:new(bf)
    Q.transfer(aw, bw, player, function() FluidContainer.Transfer(af, bf, .1) end)
    local al, bl = a:getModData()[Q.key], b:getModData()[Q.key]
    near(L.volume(al), af:getAmount(), "native large source")
    near(L.volume(bl), bf:getAmount(), "native small target")
    near(L.budget(al,"poisonPower") + L.budget(bl,"poisonPower"), 100, "native conserved poison")
    near(L.budget(al,"calories") + L.budget(bl,"calories"), 5000, "native conserved nutrition")
    near(af:getRainCatcher(), 0, "tracked rain protection")
    print("[HCRQuality160] native 64 L fractional transfer PASS")
    Q.transport.JuiceApple = nil
    local drinkSource, drinkTarget = instanceItem("Base.WaterBottle"), instanceItem("Base.WaterBottle")
    local ds, dt = drinkSource:getFluidContainer(), drinkTarget:getFluidContainer()
    ds:Empty(); dt:Empty(); ds:addFluid("HCRJuiceApple", 1)
    near(ds:getProperties():getCalories(), 0, "transport calories must be neutral")
    near(ds:getProperties():getThirstChange(), 0, "transport thirst must be neutral")
    Q.store(drinkSource, ds, L.batch("HCRJuiceApple", 1, snapshot, getGameTime():getWorldAgeHours()))
    local inv = player:getInventory()
    inv:AddItem(drinkSource); inv:AddItem(drinkTarget)
    local sw, tw = ISFluidContainer:new(ds), ISFluidContainer:new(dt)
    local action = ISFluidTransferAction:new(player, sw, ds, tw, dt, .4)
    action.getJobDelta = function() return .5 end
    action:update()
    near(ds:getAmount(), .8, "progressive source")
    near(dt:getAmount(), .2, "progressive target")
    near(L.budget(drinkTarget:getModData()[Q.key], "poisonPower"), 20, "interrupted transfer poison")
    -- Stop at partial progress, then create a separate continuation action.
    action:stop()
    action = ISFluidTransferAction:new(player, sw, ds, tw, dt, .2)
    action:complete()
    near(dt:getAmount(), .4, "resumed target")
    near(L.budget(drinkTarget:getModData()[Q.key], "poisonPower"), 40, "resumed poison")
    local drink = ISDrinkFluidAction:new(player, drinkTarget, .5)
    stats:set(CharacterStat.POISON, 0)
    nutrition:setCalories(0)
    drink:updateEat(1)
    near(dt:getAmount(), .2, "native action drank volume")
    near(nutrition:getCalories(), 1000, "native action drank calories")
    near(stats:get(CharacterStat.POISON), expectedPoison*20, "native action drank poison")
    near(L.budget(drinkTarget:getModData()[Q.key], "poisonPower"), 20, "remaining poison")
    local empty = ISFluidEmptyAction:new(player, dt)
    empty:updateEmpty(.5)
    near(dt:getAmount(), .1, "partial empty")
    empty:complete()
    assert(drinkTarget:getModData()[Q.key] == nil, "empty vessel retained old quality")
    inv:Remove(drinkTarget)
    inv:Remove(drinkSource)
    print("[HCRQuality160] native progressive transfer/drink/empty actions PASS")

    local precise=inv:AddItem("Base.WaterBottle")
    local pf=precise:getFluidContainer();pf:Empty()
    local capacity=pf:getCapacity()
    pf:addFluid("HCRJuiceApple",capacity)
    Q.store(precise,pf,L.batch("HCRJuiceApple",capacity,snapshot,getGameTime():getWorldAgeHours()))
    nutrition:setCalories(0);stats:set(CharacterStat.POISON,0)
    local beforeRaw=Q.rawAmount(pf)
    Q.remove(precise,player,function() pf:removeFluid(.0004,false) end,true,false)
    local actual=beforeRaw-Q.rawAmount(pf)
    near(pf:getAmount(),capacity,"native full snap should hide this small sip")
    near(nutrition:getCalories(),5000*actual/beforeRaw,"hidden sip calories")
    near(stats:get(CharacterStat.POISON),expectedPoison*100*actual/beforeRaw,"hidden sip poison")
    -- Last trace pruning removes the whole component; its full remaining dose
    -- must be accounted for instead of silently lost in water dilution.
    Q.remove(precise,player,function() pf:Empty() end,false)
    pf:addFluid("HCRJuiceApple",.00011);pf:addFluid(Fluid.Water,.9)
    local traceFood=L.copy(snapshot);traceFood.calories=500 -- below native nutrition cap 3700
    Q.store(precise,pf,L.batch("HCRJuiceApple",pf:getSpecificFluidAmount(Fluid.Get("HCRJuiceApple")),traceFood,getGameTime():getWorldAgeHours()))
    nutrition:setCalories(0);stats:set(CharacterStat.POISON,0)
    Q.remove(precise,player,function() pf:removeFluid(.1,false) end,true,false)
    assert(not precise:getModData()[Q.key],"Pruned component retained stale quality")
    near(nutrition:getCalories(),500,"final trace calories")
    near(stats:get(CharacterStat.POISON),expectedPoison*100,"final trace poison")
    inv:Remove(precise)
    print("[HCRQuality160] native near-full rounding and final-trace accounting PASS")

    local tinySource=inv:AddItem("Base.WaterBottle")
    local tinyTarget=inv:AddItem("Base.WaterBottle")
    local fs,ft=tinySource:getFluidContainer(),tinyTarget:getFluidContainer()
    fs:Empty();ft:Empty();fs:setCapacity(1);ft:setCapacity(1)
    -- Reverse native iteration adds Water first. Near-full snap then suppresses
    -- the last Apple marker, while its dose must still arrive at the receiver.
    fs:addFluid("HCRJuiceApple",.0005);fs:addFluid(Fluid.Water,.9995)
    Q.store(tinySource,fs,L.batch("HCRJuiceApple",fs:getSpecificFluidAmount(Fluid.Get("HCRJuiceApple")),traceFood,getGameTime():getWorldAgeHours()))
    Q.transfer(ISFluidContainer:new(fs),ISFluidContainer:new(ft),player,function() FluidContainer.Transfer(fs,ft,1) end)
    assert(fs:isEmpty() and not tinySource:getModData()[Q.key])
    near(ft:getSpecificFluidAmount(Fluid.Get("HCRJuiceApple")),0,"native clipped last marker")
    near(L.budget(tinyTarget:getModData()[Q.key],"poisonPower"),100,"clipped marker dose")
    nutrition:setCalories(0);stats:set(CharacterStat.POISON,0)
    local raw=Q.rawAmount(ft)
    Q.remove(tinyTarget,player,function() ft:removeFluid(.25,false) end,true,false)
    local fraction=(raw-Q.rawAmount(ft))/raw
    near(nutrition:getCalories(),500*fraction,"trace in water calories")
    near(stats:get(CharacterStat.POISON),expectedPoison*100*fraction,"trace in water poison")
    Q.transfer(ISFluidContainer:new(ft),ISFluidContainer:new(fs),player,function() FluidContainer.Transfer(ft,fs) end)
    assert(not tinyTarget:getModData()[Q.key])
    near(L.budget(tinySource:getModData()[Q.key],"poisonPower"),100*(1-fraction),"trace second pour")
    Q.remove(tinySource,player,function() fs:Empty() end,false)
    assert(not tinySource:getModData()[Q.key],"Empty vessel retained invisible dose")
    inv:Remove(tinySource);inv:Remove(tinyTarget)
    print("[HCRQuality160] native clipped marker, diluted sip, next pour and empty reset PASS")
    stats:set(CharacterStat.POISON, 0)
    stats:set(CharacterStat.PAIN, 0)
    print("[HCRQuality160] ALL PASS")
end

